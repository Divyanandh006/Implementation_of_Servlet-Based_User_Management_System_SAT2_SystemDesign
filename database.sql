CREATE DATABASE IF NOT EXISTS library_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE library_db;

CREATE TABLE IF NOT EXISTS admins (
 id INT AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role ENUM('ADMIN','LIBRARIAN') NOT NULL DEFAULT 'ADMIN',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS members (
 id INT AUTO_INCREMENT PRIMARY KEY,
 full_name VARCHAR(150) NOT NULL,
 email VARCHAR(180) NOT NULL UNIQUE,
 phone VARCHAR(30),
 status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS books (
 id INT AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(220) NOT NULL,
 author VARCHAR(180) NOT NULL,
 isbn VARCHAR(40) UNIQUE,
 total_copies INT NOT NULL DEFAULT 1,
 available_copies INT NOT NULL DEFAULT 1,
 digital_url VARCHAR(700),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CHECK(total_copies >= 0),
 CHECK(available_copies >= 0 AND available_copies <= total_copies)
);
CREATE TABLE IF NOT EXISTS loans (
 id INT AUTO_INCREMENT PRIMARY KEY,
 member_id INT NOT NULL,
 book_id INT NOT NULL,
 checkout_date DATE NOT NULL,
 due_date DATE NOT NULL,
 return_date DATE,
 status ENUM('BORROWED','RETURNED') NOT NULL DEFAULT 'BORROWED',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(member_id) REFERENCES members(id) ON DELETE RESTRICT,
 FOREIGN KEY(book_id) REFERENCES books(id) ON DELETE RESTRICT,
 INDEX idx_loans_status_due(status,due_date)
);
CREATE TABLE IF NOT EXISTS reservations (
 id INT AUTO_INCREMENT PRIMARY KEY,
 member_id INT NOT NULL,
 book_id INT NOT NULL,
 status ENUM('WAITING','CANCELLED','FULFILLED') NOT NULL DEFAULT 'WAITING',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(member_id) REFERENCES members(id) ON DELETE RESTRICT,
 FOREIGN KEY(book_id) REFERENCES books(id) ON DELETE RESTRICT,
 INDEX idx_reservations_queue(book_id,status,created_at)
);
CREATE TABLE IF NOT EXISTS fines (
 id INT AUTO_INCREMENT PRIMARY KEY,
 loan_id INT NOT NULL,
 amount DECIMAL(10,2) NOT NULL,
 paid BOOLEAN NOT NULL DEFAULT FALSE,
 paid_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(loan_id) REFERENCES loans(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS digital_licences (
 id INT AUTO_INCREMENT PRIMARY KEY,
 book_id INT NOT NULL,
 format VARCHAR(30) NOT NULL,
 digital_url VARCHAR(700) NOT NULL,
 concurrent_limit INT NOT NULL DEFAULT 1,
 active_count INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(book_id) REFERENCES books(id) ON DELETE CASCADE,
 CHECK(concurrent_limit > 0),
 CHECK(active_count >= 0 AND active_count <= concurrent_limit)
);
